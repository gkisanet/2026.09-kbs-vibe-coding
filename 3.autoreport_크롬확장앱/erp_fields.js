// ---------------------------------------------------------------------------
// ERP 페이지 라우팅 (뉴스 vs 프로그램)
// ---------------------------------------------------------------------------
// 뉴스 프로그램(NEWS)  → ins_res_reg_0320.htm (ZRESOGU=K003, SCREEN_NO=0300)
// 일반 프로그램        → ins_res_reg_0200.htm (ZRESOGU=K001, SCREEN_NO=0200)
// ---------------------------------------------------------------------------
const ERP_BASE_URL = 'https://erp.kbs.co.kr/kbs(bD1rbyZjPTMwMA==)/zweb_ps';
const ERP_ZORGEH = '50021098';  // 기술국(청주) 조직 코드

const ERP_PAGES = {
	news: {
		page: 'ins_res_reg_0320.htm',
		ZRESOGU: 'K003',
		SCREEN_NO: '0300'
	},
	program: {
		page: 'ins_res_reg_0200.htm',
		ZRESOGU: 'K001',
		SCREEN_NO: '0200'
	}
};

/**
 * PGM명을 기반으로 뉴스 vs 프로그램 구분
 * @param {string} pgmName - 프로그램명
 * @returns {'news'|'program'}
 */
function classifyProgram(pgmName) {
	const name = (pgmName || '').toUpperCase();
	if (name.includes('NEWS') || name.includes('뉴스')) return 'news';
	return 'program';
}

/**
 * ERP 등록 페이지 URL 생성
 * @param {'news'|'program'} type - 분류
 * @param {string} dateStr - 실적일자 YYYYMMDD
 * @returns {string} 완성된 URL
 */
function buildErpUrl(type, dateStr) {
	const cfg = ERP_PAGES[type];
	const fromDate = dateStr.slice(0, 4) + '/' + dateStr.slice(4, 6) + '/01';
	const toDate = dateStr.slice(0, 4) + '/' + dateStr.slice(4, 6) + '/28';
	return `${ERP_BASE_URL}/${cfg.page}?ZORGEH=${ERP_ZORGEH}&ZRESOGU=${cfg.ZRESOGU}&SCREEN_NO=${cfg.SCREEN_NO}&MODE=R0&ZUSDT_F=${fromDate}&ZUSDT_T=${toDate}&ZUSDT=${dateStr}&ZCOD2=&PERNR=`;
}

/**
 * 목록 페이지 URL 생성
 */
function buildErpListUrl(zresogu, fromDate, toDate) {
	return `${ERP_BASE_URL}/ins_res_list.htm?ZORGEH=${ERP_ZORGEH}&ZRESOGU=${zresogu}&ZUSDT_F=${fromDate}&ZUSDT_T=${toDate}&ZCOD2=&PERNR=`;
}

